#!/usr/bin/env python3
"""Generate src/unicode_tables.hpp from the Unicode Character Database.

Usage:
    gen_unicode_tables.py UCD_DIR > src/unicode_tables.hpp
    clang-format --style=file -i src/unicode_tables.hpp

UCD_DIR must contain EastAsianWidth.txt and DerivedGeneralCategory.txt from
https://www.unicode.org/Public/<version>/ucd/ (the latter lives in
extracted/). The version is read from the files' headers.

The tables follow xfce4-terminal (VTE), cx's reference terminal, which
measures one code point at a time: East Asian Width W/F is two columns;
Mn, Me and Hangul medial/final jamo are zero-width marks drawn onto the
preceding character; Cf characters are zero width as well, but cx shows
them as escapes, together with Zl, Zp and the C1 controls. VTE 0.84 uses Unicode
15.1 (verified against the terminal: U+1FAE9 and U+2630, wide since 16.0,
are narrow there).
"""
import os
import re
import sys


def load(path, pred):
    cps = set()
    version = None
    with open(path, encoding="utf-8") as f:
        for line in f:
            if version is None:
                m = re.search(r"-(\d+\.\d+\.\d+)\.txt", line)
                if m:
                    version = m.group(1)
            line = line.split("#")[0].strip()
            if not line:
                continue
            rng, val = (x.strip() for x in line.split(";"))
            if pred(val):
                a, _, b = rng.partition("..")
                cps.update(range(int(a, 16), int(b or a, 16) + 1))
    return cps, version


def ranges(cps):
    out = []
    for cp in sorted(cps):
        if out and out[-1][1] + 1 == cp:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def main():
    ucd = sys.argv[1]
    wide, v1 = load(os.path.join(ucd, "EastAsianWidth.txt"), lambda v: v in ("W", "F"))
    # Unassigned code points in these blocks default to W (see the header
    # of EastAsianWidth.txt).
    for a, b in [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF),
                 (0x20000, 0x2FFFD), (0x30000, 0x3FFFD)]:
        wide.update(range(a, b + 1))
    path = os.path.join(ucd, "DerivedGeneralCategory.txt")
    marks, v2 = load(path, lambda v: v in ("Mn", "Me"))
    marks.update(range(0x1160, 0x1200))  # Hangul medial vowels / final consonants
    # Shown as escapes: invisible format characters (Cf), the line and
    # paragraph separators (Zl, Zp), and the C1 controls, which a terminal
    # may act on (U+009B is CSI).
    escaped, _ = load(path, lambda v: v in ("Cf", "Zl", "Zp"))
    escaped.update(range(0x80, 0xA0))
    assert v1 == v2, (v1, v2)
    assert not (marks & escaped)
    # A few marks are also W (U+302A..302D, U+3099..309A, U+16FE4); like
    # VTE, zero width wins.
    wide -= marks | escaped

    entries = sorted([(a, b, "Wide") for a, b in ranges(wide)]
                     + [(a, b, "Combining") for a, b in ranges(marks)]
                     + [(a, b, "Escaped") for a, b in ranges(escaped)])
    body = "\n".join(f"      {{0x{a:X}, 0x{b:X}, {cls}}}," for a, b, cls in entries)

    print(f"""#pragma once

/**
 * @file unicode_tables.hpp
 * @brief Code point classes for display, from Unicode {v1}.
 *
 * Generated by tools/gen_unicode_tables.py — do not edit by hand.
 */

#include <array>
#include <cstdint>

/** @brief How a code point is displayed. */
enum class CodepointClass : uint8_t {{
  Normal,    /**< One column. */
  Wide,      /**< East Asian Width W or F: two columns. */
  Combining, /**< Mn, Me, Hangul medial/final jamo: zero width, drawn onto the previous character. */
  Escaped,   /**< Cf, Zl, Zp and C1 controls: invisible or acted on by a terminal; shown as an escape. */
}};

/** @brief Inclusive code point range [first, last] of one class. */
struct CodepointClassRange {{
  uint32_t first;
  uint32_t last;
  CodepointClass cls;
}};

/**
 * @brief Every code point that is not CodepointClass::Normal, as sorted,
 *        disjoint ranges. Look up through codepointClass() in utf8.hpp.
 */
inline constexpr auto kCodepointClasses = [] {{
  using enum CodepointClass;
  return std::to_array<CodepointClassRange>({{
{body}
  }});
}}();""")


if __name__ == "__main__":
    main()
