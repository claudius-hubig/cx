#!/usr/bin/env python3
"""Generate src/unicode_tables.hpp from the Unicode Character Database.

Usage:
    gen_unicode_tables.py UCD_DIR > src/unicode_tables.hpp
    clang-format --style=file -i src/unicode_tables.hpp

UCD_DIR must contain EastAsianWidth.txt and DerivedGeneralCategory.txt from
https://www.unicode.org/Public/<version>/ucd/ (the latter lives in
extracted/). The version is read from the files' headers.

The tables follow xfce4-terminal (VTE), cx's reference terminal, which
measures one code point at a time: East Asian Width W/F is two columns;
Mn, Me and Hangul medial/final jamo are zero-width marks drawn onto the
preceding character; Cf characters are zero width as well, but cx shows
them as escapes, so they get a table of their own. VTE 0.84 uses Unicode
15.1 (verified against the terminal: U+1FAE9 and U+2630, wide since 16.0,
are narrow there).
"""
import os
import re
import sys


def load(path, pred):
    cps = set()
    version = None
    with open(path, encoding="utf-8") as f:
        for line in f:
            if version is None:
                m = re.search(r"-(\d+\.\d+\.\d+)\.txt", line)
                if m:
                    version = m.group(1)
            line = line.split("#")[0].strip()
            if not line:
                continue
            rng, val = (x.strip() for x in line.split(";"))
            if pred(val):
                a, _, b = rng.partition("..")
                cps.update(range(int(a, 16), int(b or a, 16) + 1))
    return cps, version


def ranges(cps):
    out = []
    for cp in sorted(cps):
        if out and out[-1][1] + 1 == cp:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def table(name, doc, cps):
    items = [f"{{0x{a:X}, 0x{b:X}}}" for a, b in ranges(cps)]
    lines, cur = [], "   "
    for it in items:
        if len(cur) + len(it) + 2 > 100:
            lines.append(cur)
            cur = "   "
        cur += " " + it + ","
    lines.append(cur)
    body = "\n".join(lines)
    return f"/** @brief {doc} */\ninline constexpr auto {name} = std::to_array<CodepointRange>({{\n{body}\n}});\n"


def main():
    ucd = sys.argv[1]
    wide, v1 = load(os.path.join(ucd, "EastAsianWidth.txt"), lambda v: v in ("W", "F"))
    # Unassigned code points in these blocks default to W (see the header
    # of EastAsianWidth.txt).
    for a, b in [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF),
                 (0x20000, 0x2FFFD), (0x30000, 0x3FFFD)]:
        wide.update(range(a, b + 1))
    path = os.path.join(ucd, "DerivedGeneralCategory.txt")
    marks, v2 = load(path, lambda v: v in ("Mn", "Me"))
    marks.update(range(0x1160, 0x1200))  # Hangul medial vowels / final consonants
    fmt, _ = load(path, lambda v: v == "Cf")
    assert v1 == v2, (v1, v2)
    assert not (marks & fmt)
    # A few marks are also W (U+302A..302D, U+3099..309A, U+16FE4); like
    # VTE, zero width wins.
    wide -= marks | fmt

    print(f"""#pragma once

/**
 * @file unicode_tables.hpp
 * @brief Code point classes for display width, from Unicode {v1}.
 *
 * Generated by tools/gen_unicode_tables.py — do not edit by hand.
 */

#include <array>
#include <cstddef>
#include <cstdint>
#include <span>

/** @brief Inclusive code point range [first, last]. */
struct CodepointRange {{
  uint32_t first;
  uint32_t last;
}};

/** @brief True if @p cp lies in one of @p table's sorted, disjoint ranges. */
inline constexpr bool inRanges(std::span<CodepointRange const> table, uint32_t cp) {{
  std::size_t lo = 0, hi = table.size();
  while (lo < hi) {{
    auto mid = (lo + hi) / 2;
    if (table[mid].first <= cp)
      lo = mid + 1;
    else
      hi = mid;
  }}
  return lo > 0 && cp <= table[lo - 1].last;
}}
""")
    print(table("kWideRanges", "East Asian Width W or F: two columns wide.", wide))
    print(table("kCombiningRanges",
                "Mn, Me and Hangul medial/final jamo: zero width, drawn onto the preceding character.",
                marks))
    print(table("kFormatRanges", "Cf: invisible format characters (zero width in the terminal).", fmt), end="")


if __name__ == "__main__":
    main()
